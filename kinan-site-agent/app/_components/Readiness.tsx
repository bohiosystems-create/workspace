"use client";
/**
 * System check — is everything the demo depends on working right now? One screen, live checks, with the fix next
 * to anything that is not. Plus "Prepare today's brief" (EN + AR, narrated) and "Reset demo data", and the
 * rehearsal script. Reached from the profile sheet.
 */
import { useCallback, useEffect, useState } from "react";
import { Icon, Logo } from "./icons";
import type { GenProject, GenResult } from "@/lib/model3d/store";

type Status = "ok" | "warn" | "fail";
interface Check { id: string; label: string; status: Status; detail: string; fix?: string; ms?: number }
interface Readiness { at: string; deep: boolean; checks: Check[]; score: { ok: number; warn: number; fail: number; total: number }; standalone?: boolean; error?: string;
  join?: { number: string; name: string | null; code: string | null; url: string; qr: string; test: boolean; open: "code" | "all" | "list" } }

const SCRIPT: [string, string][] = [
  ["Open on the phone", "Projects → Kinan Heights. The site map: pins are documents and issues; tap Tower A, then 3D to show the model being built day by day (▶ on the timeline)."],
  ["WhatsApp", "From an allowed phone: 'hi' → pick Kinan Heights → 'what's late on the critical path?' Then a photo of a slab with the caption 'Tower A L15 slab at 60%' → it is filed as evidence and the schedule moves. Then a voice note."],
  ["Project schedule", "Show the critical path, the Site updates list (the WhatsApp update you just sent is there, with the photo), then Procurement → packages at risk."],
  ["Documents", "Open a drawing, leave a note by voice (microphone), and show the photo you sent with its AI reading. Upload one of the sample site documents (RFI-0163) and ask what the engineer answered."],
  ["Ask the agent", "'Which deliveries are delayed this week and what do they block?' — answered from the data with the source named."],
  ["Briefs → ▶ Play", "Play today's brief (prepare it below first). Switch to العربية and play again. Ask the presenter a question by voice mid-way."],
  ["New project", "Open a project you generated earlier from a document pack (generate it before the meeting, not live — the Kinan Marina Walk sample pack takes 1–3 minutes), play its 4D, show What it read."],
];

export default function Readiness({ onBack, onReset, onProject }: { onBack: () => void; onReset: () => void; onProject: (p: GenProject) => void }) {
  const [r, setR] = useState<Readiness | null>(null);
  const [room, setRoom] = useState(false); // the join QR full screen, for the projector
  useEffect(() => { if (!room) return; const k = (e: KeyboardEvent) => e.key === "Escape" && setRoom(false); window.addEventListener("keydown", k); return () => window.removeEventListener("keydown", k); }, [room]);
  const [busy, setBusy] = useState<string | null>(null);
  const [t0, setT0] = useState(0); const [now, setNow] = useState(0);
  useEffect(() => { if (busy !== "sample") return; const id = setInterval(() => setNow(Date.now()), 500); return () => clearInterval(id); }, [busy]);
  const post = async (body: Record<string, unknown>) => { const j = await fetch("/api/ready", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) }).then((x) => x.json()); if (j.error) throw new Error(j.error); return j; };
  /** Real AI read of the Marina Walk pack; the project is kept like any other generated project. */
  const sample = async () => {
    setBusy("sample"); setMsg(null); setT0(Date.now()); setNow(Date.now());
    try {
      const j = (await post({ action: "sample-project" })) as { docs: string[]; result: GenResult };
      onProject({ id: `p${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`, createdAt: new Date().toISOString(), docs: j.docs, result: j.result });
      setMsg({ text: `Kinan Marina Walk generated by ${j.result.engine}${j.result.model ? ` (${j.result.model})` : ""} in ${Math.round(j.result.ms / 1000)} s: ${j.result.spec.buildings.length} buildings, ${j.result.spec.schedule?.activities?.length ?? 0} activities${j.result.warnings?.length ? ` · ${j.result.warnings.length} warning${j.result.warnings.length === 1 ? "" : "s"} (see What it read)` : ""}. It is on the Projects page.` });
      await load();
    } catch (e) { setMsg({ text: (e as Error).message, bad: true }); }
    finally { setBusy(null); }
  };
  const waTest = async () => {
    setBusy("wa"); setMsg(null);
    try { const j = (await post({ action: "wa-test" })) as { to: string }; setMsg({ text: `WhatsApp test sent to ${j.to}. Check the phone: if it arrived, token, number and recipient all work.` }); }
    catch (e) { setMsg({ text: (e as Error).message, bad: true }); }
    finally { setBusy(null); }
  };
  const dropGuests = async () => {
    setBusy("guests"); setMsg(null);
    try { const j = (await post({ action: "remove-guests" })) as { removed: number }; setMsg({ text: `${j.removed} guest${j.removed === 1 ? "" : "s"} removed. The join code still works for new people until you change or remove it.` }); await load(); }
    catch (e) { setMsg({ text: (e as Error).message, bad: true }); }
    finally { setBusy(null); }
  };
  const hear = async (lang: "en" | "ar") => {
    setBusy(`voice-${lang}`); setMsg(null);
    try { const j = (await post({ action: "voice-sample", lang })) as { audio: string }; await new Audio(`data:audio/mpeg;base64,${j.audio}`).play(); }
    catch (e) { setMsg({ text: (e as Error).message, bad: true }); }
    finally { setBusy(null); }
  };
  const [msg, setMsg] = useState<{ text: string; bad?: boolean } | null>(null);
  const [confirm, setConfirm] = useState(false);
  const load = useCallback(async (deep = false) => {
    setBusy(deep ? "deep" : "load"); setMsg(null);
    try { const j = (await fetch(`/api/ready${deep ? "?deep=1" : ""}`, { cache: "no-store" }).then((x) => x.json())) as Readiness; if (j.error) setMsg({ text: j.error, bad: true }); else setR(j); }
    catch { setMsg({ text: "Could not reach the server.", bad: true }); }
    finally { setBusy(null); }
  }, []);
  useEffect(() => { load(); }, [load]);
  const act = async (action: "prepare" | "reset") => {
    setBusy(action); setMsg(null); setConfirm(false);
    try {
      const j = await fetch("/api/ready", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ action, by: "System check" }) }).then((x) => x.json());
      if (j.error) { setMsg({ text: j.error, bad: true }); return; }
      if (action === "prepare") setMsg({ text: `Today's brief is built and narrated in English and Arabic — Briefs → ▶ Play opens instantly.` });
      else { setMsg({ text: `Demo data reset: ${j.reset.docs} seeded documents, ${j.reset.notes} notes, data date ${j.reset.dataDate}.` }); onReset(); }
      await load();
    } catch { setMsg({ text: "Network error — try again.", bad: true }); }
    finally { setBusy(null); }
  };
  const pct = r ? Math.round(((r.score.ok + r.score.warn * 0.5) / Math.max(1, r.score.total)) * 100) : null;
  const tone = r ? (r.score.fail ? "bad" : r.score.warn ? "warn" : "good") : "";
  return (
    <div className="home ready">
      <button className="crumb" onClick={onBack}><Icon name="back" />Back</button>
      <div className="home-head"><div><h1>System check</h1><p>Everything the demo depends on, checked live. Red needs fixing before the meeting; amber is a choice; green is ready.</p></div></div>
      {msg && <div className={msg.bad ? "studio-err" : "studio-ok"} role="status">{msg.text}</div>}
      {r?.standalone && <div className="rpt-alert">This is the standalone file: there is no server to check. Open the deployed app for the full check.</div>}
      <div className="ready-top">
        <div className={"ready-score " + tone}><b>{pct ?? "…"}</b><span>{r ? `${r.score.ok} ready · ${r.score.warn} to decide · ${r.score.fail} to fix` : "checking…"}</span>{r && <em>{r.deep ? "deep check" : "quick check"} · {new Date(r.at).toLocaleTimeString("en-GB", { hour: "2-digit", minute: "2-digit" })}</em>}</div>
        <div className="ready-acts">
          <button className="studio-add" disabled={!!busy || !!r?.standalone} onClick={() => load(true)}>{busy === "deep" ? "Calling the AI and ElevenLabs…" : "Deep check: real AI call + speech"}</button>
          <button className="studio-add" disabled={!!busy || !!r?.standalone} onClick={() => act("prepare")}>{busy === "prepare" ? "Building and narrating (up to 2 min)…" : "Prepare today's brief (EN + AR)"}</button>
          {!confirm ? <button className="studio-back" disabled={!!busy || !!r?.standalone} onClick={() => setConfirm(true)}>Reset demo data…</button>
            : <span className="ready-confirm">Uploads, notes, pins and site updates will go; briefs stay. <button className="studio-go" disabled={!!busy} onClick={() => act("reset")}>{busy === "reset" ? "Resetting…" : "Yes, reset"}</button><button className="mini" onClick={() => setConfirm(false)}>Keep</button></span>}
          <button className="mini" disabled={!!busy} onClick={() => load(false)}>Re-check</button>
          <div className="ready-sub">Rehearse for real</div>
          <button className="studio-add" disabled={!!busy || !!r?.standalone} onClick={sample}>{busy === "sample" ? `Reading the Marina Walk pack with AI… ${Math.floor((now - t0) / 1000)} s` : "Generate the sample project (AI, 1–3 min)"}</button>
          <button className="studio-add" disabled={!!busy || !!r?.standalone} onClick={waTest}>{busy === "wa" ? "Sending…" : "Send a WhatsApp test to the first allowed phone"}</button>
          <span className="ready-voices"><button className="mini" disabled={!!busy || !!r?.standalone} onClick={() => hear("en")}>{busy === "voice-en" ? "…" : "▶ English voice"}</button><button className="mini" disabled={!!busy || !!r?.standalone} onClick={() => hear("ar")}>{busy === "voice-ar" ? "…" : "▶ الصوت العربي"}</button><button className="mini" disabled={!!busy || !!r?.standalone} onClick={dropGuests}>{busy === "guests" ? "…" : "Remove WhatsApp guests"}</button></span>
        </div>
      </div>
      {r?.join && (
        <section className="ready-join">
          <div className="rj-qr" aria-label="QR code: chat with the agent on WhatsApp" dangerouslySetInnerHTML={{ __html: r.join.qr }} />
          <div className="rj-text">
            <div className="rpt-label">Join on WhatsApp</div>
            <b className="rj-num">{r.join.number}</b>{r.join.name && <span className="muted"> · {r.join.name}</span>}
            <p className="muted small">Scanning opens WhatsApp with {r.join.code ? <>the code <b>{r.join.code}</b></> : <>“hi”</>} already typed — people just press send.{" "}
              {r.join.open === "code" ? "Anyone with the code gets in as a guest." : r.join.open === "all" ? "Anyone can talk to it (WHATSAPP_ALLOW_ALL)." : "Only the allowed numbers get answers — set WHATSAPP_JOIN_CODE to let the room in."}</p>
            {r.join.test && <p className="rj-warn">This is Meta&rsquo;s test number: only phones registered as test recipients get replies. Connect the real business number before showing this to a room.</p>}
            <div className="rj-acts">
              <button className="studio-add" onClick={() => setRoom(true)}>Show full screen for the room</button>
              <button className="mini" onClick={async () => { const { saveFile } = await import("./deck/saveFile"); await saveFile("kinan-onsite-agent-whatsapp-qr.svg", r.join!.qr, "image/svg+xml"); }}>Download QR</button>
              <button className="mini" onClick={() => { navigator.clipboard?.writeText(r.join!.url).then(() => setMsg({ text: "Link copied." }), () => setMsg({ text: r.join!.url })); }}>Copy link</button>
            </div>
          </div>
        </section>
      )}
      {room && r?.join && (
        <div className="rj-room" role="dialog" aria-label="Join the Kinan Onsite Agent on WhatsApp" onClick={() => setRoom(false)}>
          <div className="rj-room-in" onClick={(e) => e.stopPropagation()}>
            <Logo height={44} color="#ffffff" />
            <h2>Talk to the Kinan Onsite Agent</h2>
            <p className="rj-ar" dir="rtl">تحدّثوا مع الوكيل الميداني من كنان</p>
            <div className="rj-big" dangerouslySetInnerHTML={{ __html: r.join.qr }} />
            <ol>
              <li>Scan with your phone camera</li>
              <li>WhatsApp opens with {r.join.code ? <b>{r.join.code}</b> : <b>hi</b>} typed — press send</li>
              <li>Pick Kinan Heights and ask anything: “what&rsquo;s late on Tower A?”, a photo, a voice note</li>
            </ol>
            <div className="rj-foot">{r.join.number}{r.join.code ? <> · code <b>{r.join.code}</b></> : null}</div>
            <button className="rj-x" onClick={() => setRoom(false)} aria-label="Close">×</button>
          </div>
        </div>
      )}
      <ul className="ready-list">
        {(r?.checks ?? []).map((c) => (
          <li key={c.id} className={c.status}>
            <span className="st" aria-hidden="true">{c.status === "ok" ? "✓" : c.status === "warn" ? "!" : "✕"}</span>
            <span className="t"><b>{c.label}</b><em>{c.detail}</em>{c.fix && <i>{c.fix}</i>}</span>
          </li>
        ))}
        {!r && !msg && <li className="empty">Checking…</li>}
      </ul>
      <div className="lbl">Rehearsal script <span className="dd">seven stops, about twelve minutes</span></div>
      <ol className="ready-script">{SCRIPT.map(([h, t]) => <li key={h}><b>{h}</b><span>{t}</span></li>)}</ol>
      <p className="muted small">The demo data follows the calendar: rehearse the day before, not the week before. Generate any document-pack project before the meeting and keep it — it is saved on this device and synced to the server.</p>
    </div>
  );
}
